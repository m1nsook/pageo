import { readFileSync, readdirSync, mkdirSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { resolve, join } from "node:path";
const source = resolve(process.argv[2] ?? "../paglora-lang", "locales");
if (!existsSync(source)) throw new Error("Provide a local paglora-lang checkout, e.g. node scripts/sync-translations.mjs ../paglora-lang");
const destination = resolve("apps/desktop/src/i18n/locales");
const names = readdirSync(source).filter(n => /^[a-z]{2}(?:-[A-Z]{2})?\.json$/.test(n)).sort();
if (!names.includes("en.json")) throw new Error("Canonical en.json is required");
const packs = names.map(name => ({ name, catalog: JSON.parse(readFileSync(join(source, name), "utf8")) }));
const english = packs.find(p => p.name === "en.json").catalog.messages;
const placeholders = s => [...s.matchAll(/\{([a-z][a-zA-Z0-9_]*)\}/g)].map(x => x[1]).sort().join(",");
for (const {name,catalog} of packs) {
  if (catalog.schemaVersion !== 1 || catalog.locale !== name.slice(0,-5) || !catalog.messages) throw new Error("Invalid locale: " + name);
  for (const [key,value] of Object.entries(catalog.messages)) {
    if (!(key in english) || typeof value !== "string" || !value.trim() ||
        /[<>\x00-\x1f\x7f]/.test(value) || placeholders(value) !== placeholders(english[key]))
      throw new Error("Invalid translation in " + name + ": " + key);
  }
}
mkdirSync(destination, { recursive:true });
for (const old of readdirSync(destination).filter(n => n.endsWith(".json"))) rmSync(join(destination,old));
for (const {name,catalog} of packs) writeFileSync(join(destination,name),JSON.stringify(catalog,null,2)+"\n");
const registry = packs.map(({name,catalog}) => `    ("${catalog.locale}", include_str!("../../src/i18n/locales/${name}")),`).join("\n");
writeFileSync("apps/desktop/src-tauri/src/locale_catalogs.rs","// Generated by scripts/sync-translations.mjs.\nconst PAGLORA_LOCALE_SOURCES: &[(&str, &str)] = &[\n"+registry+"\n];\n");
console.log(`Synced ${packs.length} offline translation catalogs. Run all tests before committing.`);
